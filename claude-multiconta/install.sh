#!/bin/sh
# Installs the Claude Code multi-account setup + usage (claude-multiconta).
#   ./install.sh            installs/updates (installs claude and codex if they are missing)
#   ./install.sh --no-install  same, but without downloading claude/codex
#   ./install.sh --uninstall removes the files and the source line
# Idempotent: you can run it again after editing accounts.json.
set -eu
HERE=$(cd "$(dirname "$0")" && pwd)
BIN="$HOME/.local/bin"
CONF_DIR="$HOME/.config/claude-multiconta"
ALIASES="$CONF_DIR/aliases.sh"
MARK="# >>> claude-multiconta >>>"
SOURCE_LINE="[ -r \"$ALIASES\" ] && . \"$ALIASES\"   $MARK"

rc_files() {
  # zsh and/or bash, whichever exists; creates .bashrc if there is neither
  found=0
  for f in "$HOME/.zshrc" "$HOME/.bashrc"; do [ -f "$f" ] && { echo "$f"; found=1; }; done
  [ $found = 0 ] && { touch "$HOME/.bashrc"; echo "$HOME/.bashrc"; }
}

# --- claude and codex: install them if missing -------------------------------
have() { command -v "$1" >/dev/null 2>&1 || [ -x "$BIN/$1" ]; }

ensure_claude() {
  have claude && { echo "claude: ok ($(command -v claude || echo "$BIN/claude"))"; return; }
  echo "claude: not found, installing (official script at claude.ai/install.sh)..."
  command -v curl >/dev/null || { echo "curl is needed to install claude"; return 1; }
  curl -fsSL https://claude.ai/install.sh | bash || { echo "failed to install claude"; return 1; }
  have claude && echo "claude: installed at $BIN/claude"
}

ensure_codex() {
  # codex installed through npm/nvm only shows up in the PATH of interactive shells; look there too
  for c in "$HOME"/.nvm/versions/node/*/bin/codex "$HOME"/.npm-global/bin/codex; do
    [ -x "$c" ] && { echo "codex: ok ($c, via npm; to update: npm install -g @openai/codex)"; return; }
  done
  have codex && { echo "codex: ok ($(command -v codex || echo "$BIN/codex"))"; return; }
  if command -v npm >/dev/null 2>&1; then
    echo "codex: not found, installing via npm..."
    npm install -g @openai/codex && return
    echo "npm failed, trying the GitHub binary..."
  fi
  echo "codex: not found, downloading the official binary from GitHub (~100 MB)..."
  command -v curl >/dev/null || { echo "curl (or npm) is needed to install codex"; return 1; }
  os=$(uname -s); arch=$(uname -m)
  case "$arch" in x86_64|amd64) arch=x86_64;; aarch64|arm64) arch=aarch64;; *) echo "no binary for architecture $arch"; return 1;; esac
  case "$os" in Linux) target="$arch-unknown-linux-musl";; Darwin) target="$arch-apple-darwin";; *) echo "no binary for OS $os"; return 1;; esac
  tmp=$(mktemp -d)
  url="https://github.com/openai/codex/releases/latest/download/codex-$target.tar.gz"
  curl -fL --progress-bar -o "$tmp/codex.tgz" "$url" || { echo "download failed: $url"; rm -rf "$tmp"; return 1; }
  tar xzf "$tmp/codex.tgz" -C "$tmp" && mv "$tmp/codex-$target" "$BIN/codex" && chmod +x "$BIN/codex"
  rm -rf "$tmp"
  [ -x "$BIN/codex" ] && echo "codex: installed at $BIN/codex ($("$BIN/codex" --version 2>/dev/null))"
}

if [ "${1:-}" = "--uninstall" ]; then
  for f in $(rc_files); do
    grep -v "$MARK" "$f" > "$f.tmp" && mv "$f.tmp" "$f"
  done
  rm -f "$BIN/codex-usage-fast" "$BIN/usage-all" "$BIN/claude-last" "$BIN/orq" "$BIN/orq-run" "$BIN/orq-hook" "$BIN/claude-login-url" "$BIN/claude-whoami" "$BIN/usage-sessoes" "$BIN/usage-hist"
  rm -rf "$CONF_DIR"
  echo "removed. The accounts in ~/.claude* and ~/.codex were left untouched."
  exit 0
fi

command -v python3 >/dev/null || { echo "python3 is needed (>= 3.9 preferably): apt install python3"; exit 1; }
mkdir -p "$BIN" "$CONF_DIR"
if [ "${1:-}" != "--no-install" ]; then
  ensure_claude || echo "warning: claude not installed; install it by hand and run ./install.sh again"
  ensure_codex  || echo "warning: codex not installed; install it by hand and run ./install.sh again"
fi
cp "$HERE"/bin/codex-usage-fast "$HERE"/bin/usage-all "$HERE"/bin/claude-last "$HERE"/bin/orq "$HERE"/bin/orq-run "$HERE"/bin/orq-hook "$HERE"/bin/claude-login-url "$HERE"/bin/claude-whoami "$HERE"/bin/usage-sessoes "$HERE"/bin/usage-hist "$BIN/"
chmod +x "$BIN"/codex-usage-fast "$BIN"/usage-all "$BIN"/claude-last "$BIN"/orq "$BIN"/orq-run "$BIN"/orq-hook "$BIN"/claude-login-url "$BIN"/claude-whoami "$BIN"/usage-sessoes "$BIN"/usage-hist
cp "$HERE/accounts.json" "$CONF_DIR/accounts.json"

# generates aliases.sh from accounts.json (works in bash and zsh)
python3 - "$CONF_DIR/accounts.json" "$ALIASES" <<'PY'
import json, sys
conf = json.load(open(sys.argv[1]))
accounts = conf["accounts"]
names = [a["name"] for a in accounts]
default = conf.get("default_account")
use_tmux = conf.get("tmux", True)
if default and default not in names:
    sys.exit(f"default_account '{default}' is not in accounts")

out = ["# generated by the claude-multiconta install.sh from accounts.json — do not edit by hand",
       'case ":$PATH:" in *":$HOME/.local/bin:"*) ;; *) export PATH="$HOME/.local/bin:$PATH";; esac',
       ""]
if use_tmux:
    out += [
"# claude_run <prefix> <config_dir or empty=default> [claude args]",
"# An interactive session opens in a NEW tmux named <prefix>-<folder> (-2, -3... if it repeats);",
"# attaching is manual: tmux ls / tmux attach -t <name>. It runs DIRECTLY (without tmux) when:",
"# it is already inside tmux, there is no tmux, or it is a quick subcommand (auth, --version, -p, mcp...).",
"claude_run() {",
"    local prefix=$1 dir=$2 direct= bin base name n=1; shift 2",
"    case \"${1-}\" in auth|mcp|config|doctor|update|install|plugin|agents|-p|--print|-v|--version|-h|--help) direct=1;; esac",
'    [ -n "$TMUX" ] && direct=1',
"    command -v tmux >/dev/null 2>&1 || direct=1",
'    bin=$(claude_bin) || { echo "claude not found in the PATH" >&2; return 127; }',
'    if [ -n "$dir" ]; then set -- env CLAUDE_CONFIG_DIR="$dir" "$bin" "$@"; else set -- env -u CLAUDE_CONFIG_DIR "$bin" "$@"; fi',
'    if [ -n "$direct" ]; then "$@"; return; fi',
'    base="$prefix-${PWD##*/}"; base=${base//[^a-zA-Z0-9_-]/-}; name=$base',
'    while tmux has-session -t "=$name" 2>/dev/null; do name="$base-$((++n))"; done',
'    # the tmux server inherits the folder of whoever creates it; if it were born here, deleting this folder would break every window',
'    local here=$PWD',
'    (cd ~ && tmux new-session -s "$name" -c "$here" "$(printf \'%q \' "$@")")',
"}",
"# path of the claude binary, ignoring the `claude` function of this shell",
'claude_bin() { if [ -n "$BASH_VERSION" ]; then type -P claude; else whence -p claude; fi; }',
""]
for a in accounts:
    n, d, em = a["name"], a["config_dir"], a.get("email", "")
    if d.rstrip("/") in ("~/.claude", "$HOME/.claude"):
        env = "env -u CLAUDE_CONFIG_DIR"
    else:
        env = 'env CLAUDE_CONFIG_DIR="' + d.replace("~", "$HOME", 1) + '"'
    email = f" --email {em}" if em else ""
    prefix = "claude" if n == default else f"claude-{n}"
    out.append(f"# {a.get('label', n)}" + (f"  [tmux session {prefix}-<folder>]" if use_tmux else ""))
    if use_tmux:
        dirarg = '""' if env.startswith("env -u") else '"' + d.replace("~", "$HOME", 1) + '"'
        out.append(f'claude-{n}() {{ claude_run {prefix} {dirarg} "$@"; }}')
    else:
        out.append(f'claude-{n}() {{ {env} claude "$@"; }}')
    out += [f"alias claude-{n}-login='{env} BROWSER=\"$HOME/.local/bin/claude-login-url\" claude auth login{email}'",
            f"alias claude-usage-{n}='usage-all {n}'", ""]
if default:
    out += [f"# plain `claude` = the best account right now (usage-all --melhor: uses first the quota that expires first; -v explains).",
            f"#   CLAUDE_CONTA=gmail claude  forces an account; with no readable quota, it falls back to the default ({default}).",
            "claude() {",
            '  local acc=${CLAUDE_CONTA:-}',
            '  [ -n "$acc" ] || acc=$(usage-all --melhor 2>/dev/null)',
            f'  type "claude-$acc" >/dev/null 2>&1 || acc={default}',
            '  "claude-$acc" "$@"',
            "}", ""]

if conf.get("codex", True):
    out += ["# Codex (OpenAI)",
            "alias codex-login='codex login --device-auth'",
            "alias codex-usage='codex-usage-fast'", ""]
out += ["# Usage of all the accounts at once: it is the script ~/.local/bin/usage-all",
        "#   usage-all [-v|--verbose] [account ...]   (e.g.: usage-all work; -v = full)",
        "unalias usage-all 2>/dev/null", "",
        "# Resume the most recent conversation of this folder (list: claude-last) on the best account: it stays on the",
        "# conversation's account if it is in good shape; otherwise, on the one usage-all --melhor picks (the conversation is copied to it; the original stays)",
        "#   claude-resume [--as ACCOUNT] [-a] [N] [claude args]   N = line number from claude-last",
        "#   --as ACCOUNT: forces the account",
        "claude-resume() {",
        "  local all= as= n=1 out acc sid",
        "  while :; do",
        '    case "$1" in',
        '      -a|--all) all=-a; shift;;',
        '      --as) as=$2; shift 2;;',
        '      --as=*) as=${1#--as=}; shift;;',
        '      *) break;;',
        "    esac",
        "  done",
        '  case "$1" in ""|*[!0-9]*) ;; *) n=$1; shift;; esac',
        '  if [ -z "$as" ]; then',
        '    out=$(claude-last --pick $all "$n") || return 1',
        '    read -r acc sid <<< "$out"',
        '    as=$(usage-all --melhor --fica "$acc" 2>/dev/null)',
        '    [ -n "$as" ] || as=$acc',
        '  fi',
        '  out=$(claude-last --pick $all --as="$as" "$n") || return 1',
        '  read -r acc sid <<< "$out"',
        '  "claude-$acc" --resume "$sid" "$@"',
        "}", ""]
if conf.get("tip_on_login", True):
    out += ["case $- in *i*) echo \"💡 usage-all: Claude usage\";; esac", ""]
open(sys.argv[2], "w").write("\n".join(out))
# hooks that orq-run passes to claude with --settings (they only apply in orq's panes)
import os
hook = os.path.expanduser("~/.local/bin/orq-hook")
h = [{"hooks": [{"type": "command", "command": hook}]}]
json.dump({"hooks": {e: h for e in ("SessionStart", "UserPromptSubmit", "Stop", "Notification", "StopFailure", "SessionEnd")}},
          open(os.path.join(os.path.dirname(sys.argv[2]), "orq-hooks.json"), "w"), indent=1)
print("accounts:", ", ".join(names), "| plain `claude` =", default or "(no default)")
PY

# marks onboarding as done in each account's .claude.json: `claude auth login` writes the
# credential but not that mark, so the first `claude-<account>` opens the first-run
# wizard, which ends in a new browser login (callback on localhost) and breaks with
# "Redirect URI ... not supported". Idempotent; it does not touch accounts that already have the mark.
CLAUDE_EXE=$(command -v claude || echo "$BIN/claude")
python3 - "$CONF_DIR/accounts.json" "$CLAUDE_EXE" <<'PY'
import json, os, pathlib, subprocess, sys
conf = json.load(open(sys.argv[1])); accounts = conf["accounts"]
home = pathlib.Path.home()

def write_json(f, data):
    # .tmp + replace: Claude Code rewrites these files; never leave one half-written
    tmp = f.with_name(f.name + ".tmp")
    tmp.write_text(json.dumps(data, indent=2)); os.chmod(str(tmp), 0o600); os.replace(str(tmp), str(f))

# Terminal renderer: "default" writes the conversation to the native scrollback (tmux, iTerm,
# PgUp and the mouse wheel see everything); "fullscreen" keeps it in a buffer of its own and the
# history disappears after one screen. It is the same as typing /tui default inside Claude Code, but
# it applies to every account. "tui": false in accounts.json leaves each account as it is.
tui = conf.get("tui", "default")
for a in accounts:
    if tui is False: break
    d = pathlib.Path(os.path.expanduser(a["config_dir"].replace("$HOME", "~", 1)))
    d.mkdir(parents=True, exist_ok=True)
    f = d / "settings.json"
    try:
        st = json.loads(f.read_text()) if f.exists() else {}
    except ValueError:
        print(f"warning: {f} is not valid JSON; left it alone"); continue
    if st.get("tui") == tui: continue
    st["tui"] = tui
    write_json(f, st)
    print(f"tui={tui} in {f}")

try:
    ver = subprocess.run([sys.argv[2], "--version"], stdout=subprocess.PIPE,
                         universal_newlines=True, timeout=30).stdout.split()[0]
except Exception:
    ver = None
for a in accounts:
    d = pathlib.Path(os.path.expanduser(a["config_dir"].replace("$HOME", "~", 1)))
    d.mkdir(parents=True, exist_ok=True)
    # the account in ~/.claude keeps its state in ~/.claude.json; the others, inside the config_dir
    f = home / ".claude.json" if d.resolve() == (home / ".claude").resolve() else d / ".claude.json"
    try:
        cfg = json.loads(f.read_text()) if f.exists() else {}
    except ValueError:
        print(f"warning: {f} is not valid JSON; left it alone"); continue
    if cfg.get("hasCompletedOnboarding"):
        continue
    cfg["hasCompletedOnboarding"] = True
    if ver: cfg.setdefault("lastOnboardingVersion", ver)
    cfg.setdefault("theme", "dark")
    write_json(f, cfg)
    print(f"onboarding marked as done in {f}")
PY

# source line in the rc files: in a .zshrc with Powerlevel10k it goes BEFORE the instant prompt block
# (aliases.sh prints the tip, and p10k complains about output after that block)
for f in $(rc_files); do
  grep -qF "$MARK" "$f" && continue
  if grep -q "p10k-instant-prompt" "$f"; then
    { echo "$SOURCE_LINE"; cat "$f"; } > "$f.tmp" && mv "$f.tmp" "$f"
  else
    printf '\n%s\n' "$SOURCE_LINE" >> "$f"
  fi
  echo "source line added to $f"
done

for f in $(rc_files); do
  if grep -v "$MARK" "$f" | grep -qE '^[[:space:]]*(function[[:space:]]+)?claude[[:space:]]*\(\)'; then
    echo "warning: $f still defines a claude() function of its own; it will clash with the claude-multiconta one. Remove the old block."
  fi
done
echo
echo "installed. Open a new terminal (or: . $ALIASES) and then:"
for n in $(python3 -c "import json;print(' '.join(a['name'] for a in json.load(open('$CONF_DIR/accounts.json'))['accounts']))"); do
  echo "  claude-$n-login    # login for the $n account (open the link, paste the code)"
done
echo "  codex-login          # Codex login through device auth"
echo "  usage-all            # Claude usage, brief: one line per account, mini-bar with pace and time until the reset"
echo "  usage-all -v         # full, with bar and pace marker"
echo "  usage-all gmail      # only the chosen account (also accepts -v); codex-usage for Codex"
echo "  orq                  # opens up to 4 projects (any machine) in one window with 4 panes"
echo "  claude-last          # which account had the most recent conversation in this folder"
echo "  claude               # opens the best account right now (usage-all --melhor -v explains; CLAUDE_CONTA=x forces one)"
echo "  claude-resume        # resumes that conversation: on its own account if it is in good shape, otherwise on the best one (2 = the second)"
echo "  claude-resume --as gmail   # resumes the same conversation using another account"
