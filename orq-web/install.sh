#!/bin/sh
# Installs orq-web on this machine without pip: copies the package to ~/.local/lib/orq-web and creates
# the orq-agent and orq-web commands in ~/.local/bin. It only needs python3 (3.8+). Idempotent.
set -eu
HERE=$(cd "$(dirname "$0")" && pwd)
LIB="$HOME/.local/lib/orq-web"
BIN="$HOME/.local/bin"
command -v python3 >/dev/null || { echo "needs python3 (3.8 or later)"; exit 1; }
mkdir -p "$LIB" "$BIN"
rm -rf "$LIB/orqweb"
cp -R "$HERE/orqweb" "$LIB/orqweb"
find "$LIB/orqweb" -name __pycache__ -type d -exec rm -rf {} + 2>/dev/null || true
python3 -m compileall -q "$LIB/orqweb" >/dev/null 2>&1 || true
for cmd in orq-agent:orqweb.agent.cli orq-web:orqweb.server.cli converte-web:orqweb.convert; do
  name=${cmd%%:*}; mod=${cmd#*:}
  cat > "$BIN/$name" <<SH
#!/bin/sh
# generated by orq-web's install.sh; the code is in $LIB
PYTHONPATH="$LIB\${PYTHONPATH:+:\$PYTHONPATH}" exec python3 -m $mod "\$@"
SH
  chmod +x "$BIN/$name"
done
ver=$(python3 -c "import sys; sys.path.insert(0, '$LIB'); import orqweb; print(orqweb.__version__)")
echo "orq-web $ver installed: $BIN/orq-agent, $BIN/orq-web and $BIN/converte-web (code in $LIB)"
