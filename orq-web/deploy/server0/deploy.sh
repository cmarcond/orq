#!/bin/sh
# Starts (or updates) orq-web in a container on this machine, published only on the ZeroTier IP.
# Generates the password (if there is none) and the container's ssh_config, and makes sure ssh to this
# same machine works.
# Usage: deploy/server0/deploy.sh            (at the root of the orq-web clone, on the target machine)
set -eu
HERE=$(cd "$(dirname "$0")" && pwd)
CFG="$HOME/.config/orq-web"
CONF="${CLAUDE_MULTICONTA_CONF:-$HOME/.config/claude-multiconta/accounts.json}"
HOSTNAME_=$(hostname -s)
ZT_IP=$(ip -4 -o addr show 2>/dev/null | awk '/ zt/ {split($4,a,"/"); print a[1]; exit}')
[ -n "$ZT_IP" ] || { echo "no ZeroTier interface found (zt*)"; exit 1; }
mkdir -p "$CFG/state" "$CFG/known_hosts.d"

# password: one line, readable only by the owner. Read it with: cat ~/.config/orq-web/password
if [ ! -s "$CFG/password" ]; then
  umask 077; openssl rand -base64 18 > "$CFG/password"; umask 022
  echo "new password written to $CFG/password"
fi
chmod 600 "$CFG/password"

# ssh to this same machine (inside the container, "$HOSTNAME_" is remote)
KEY="$HOME/.ssh/id_ed25519"
[ -f "$KEY" ] || { echo "no $KEY; generate it with ssh-keygen -t ed25519"; exit 1; }
touch "$HOME/.ssh/authorized_keys"; chmod 600 "$HOME/.ssh/authorized_keys"
grep -qF "$(cut -d' ' -f2 "$KEY.pub")" "$HOME/.ssh/authorized_keys" || cat "$KEY.pub" >> "$HOME/.ssh/authorized_keys"

# the container's ssh_config: one Host per machine, with the IP resolved here (the container has neither
# this machine's /etc/hosts nor its ~/.ssh/config). Its own known_hosts, writable, with accept-new.
hosts=$(python3 -c "import json;print(' '.join(json.load(open('$CONF')).get('orq_hosts',[])))")
# what this machine's ~/.ssh/config changes for each host and the container also needs: ProxyJump and a specific
# key exchange (e.g. a machine reachable only by going through another one)
default_kex=$(ssh -G orq-host-sem-config 2>/dev/null | awk '/^kexalgorithms /{print $2}')
{
  echo "# generated by deploy.sh at $(date -Is); do not edit, run the deploy again"
  seen=" "
  for h in $hosts laptop "$HOSTNAME_"; do
    case "$seen" in *" $h "*) continue;; esac; seen="$seen$h "
    ip=$(ssh -G "$h" 2>/dev/null | awk '/^hostname /{print $2}')
    case "$ip" in ""|"$h") ip=$(getent hosts "$h" 2>/dev/null | awk '{print $1; exit}');; esac
    [ "$h" = "$HOSTNAME_" ] && ip="$ZT_IP"
    [ -n "$ip" ] || { echo "warning: could not resolve $h; skipping" >&2; continue; }
    printf 'Host %s\n    HostName %s\n    User %s\n    IdentityFile %s\n    IdentitiesOnly yes\n    StrictHostKeyChecking accept-new\n    UserKnownHostsFile %s/known_hosts\n    ConnectTimeout 8\n    ServerAliveInterval 15\n' \
      "$h" "$ip" "$(id -un)" "$KEY" "$CFG"
    jump=$(ssh -G "$h" 2>/dev/null | awk '/^proxyjump /{print $2}')
    case "$jump" in ""|none) ;; *) printf '    ProxyJump %s\n' "$jump";; esac
    kex=$(ssh -G "$h" 2>/dev/null | awk '/^kexalgorithms /{print $2}')
    [ -n "$kex" ] && [ "$kex" != "$default_kex" ] && printf '    KexAlgorithms %s\n' "$kex"
    echo
  done
} > "$CFG/ssh_config"
chmod 600 "$CFG/ssh_config"
echo "container ssh_config: $(grep -c '^Host ' "$CFG/ssh_config") machines"

cd "$HERE"
export ORQ_ZT_IP="$ZT_IP" ORQ_HOSTNAME="$HOSTNAME_" UID="$(id -u)" GID="$(id -g)" USER="$(id -un)" HOME
# CI image (GHCR) if there is a login (docker login ghcr.io with a read:packages PAT); otherwise builds here.
# ORQ_BUILD_LOCAL=1 forces a build with the code sent (before it reaches main).
if [ -z "${ORQ_BUILD_LOCAL:-}" ] && docker compose pull --quiet 2>/dev/null; then docker compose up -d; else echo "building locally"; docker compose up -d --build; fi
sleep 3
docker compose ps --format 'table {{.Name}}\t{{.Status}}'
echo
echo "orq-web at http://$ZT_IP:8765/   password: cat $CFG/password"
